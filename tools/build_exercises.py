def main() -> None:
    raw_path = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    data = json.loads(raw_path.read_text(encoding="utf-8"))
    by_id = {ex["id"]: ex for ex in data}

    result = []
    audit = []
    missing = []
    for ex_id, zh_name, body_part in SELECTED:
        ex = by_id.get(ex_id)
        if ex is None:
            missing.append((ex_id, zh_name))
            continue
        equip_zh = EQUIPMENT_ZH.get(ex["equipment"], ex["equipment"])
        target_zh = MUSCLE_ZH.get(ex.get("target", ""), ex.get("target", ""))
        muscle_group_zh = MUSCLE_ZH.get(ex.get("muscle_group", ""), ex.get("muscle_group", ""))
        secondary_zh = [
            MUSCLE_ZH.get(m, m) for m in ex.get("secondary_muscles", [])
        ]
        item = {
            "id": ex_id,
            "name": zh_name,
            "category": body_part,
            "body_part": body_part,
            "equipment": equip_zh,
            "instructions": {"zh": ex["instructions"]["zh"]},
            "instruction_steps": {"zh": ex["instruction_steps"]["zh"]},
            "muscle_group": muscle_group_zh,
            "secondary_muscles": secondary_zh,
            "target": target_zh,
            "media_id": ex["media_id"],
            "image": ex["image"],
            "gif_url": ex["gif_url"],
            "attribution": ex.get("attribution", ""),
            "created_at": ex.get("created_at", ""),
        }
        result.append(item)
        audit.append(
            {
                **item,
                "nameEn": ex["name"],
                "targetEn": ex.get("target", ""),
                "muscleGroupEn": ex.get("muscle_group", ""),
                "equipmentEn": ex["equipment"],
                "type": "有氧" if body_part == "有氧" else "无氧",
            }
        )

    result.sort(key=lambda x: (x["body_part"], x["name"]))
    audit.sort(key=lambda x: (x["body_part"], x["name"]))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    audit_path = out_path.with_name(out_path.stem + "_audit.json")
    audit_path.write_text(
        json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"生成动作数: {len(result)} / {len(SELECTED)}")
    if missing:
        print("未找到:")
        for ex_id, name in missing:
            print(f"  {ex_id} {name}")
    print("已写入:", out_path)
    print("审计文件:", audit_path)


if __name__ == "__main__":
    main()
