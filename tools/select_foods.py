def best_match(rows, keywords, excludes):
    best = None
    best_score = -1
    for r in rows:
        n = normalize(r["name"])
        orig = CC.convert(r["name"])
        if not n:
            continue
        if any(e in orig for e in excludes):
            continue
        hits = sum(1 for k in keywords if k in n)
        if hits == 0:
            continue
        score = hits * 100 - len(n)
        if "平均" in r["name"]:
            score += 30
        if score > best_score:
            best = r
            best_score = score
    return best


def main() -> None:
    raw_path = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    rows = json.loads(raw_path.read_text(encoding="utf-8"))

    # 去重目标名（保留第一次出现）
    seen_names: set[str] = set()
    targets = []
    for name, keywords, excludes in TARGETS:
        if name in seen_names:
            continue
        seen_names.add(name)
        targets.append((name, keywords, excludes))

    result = []
    audit = []
    missing = []
    used: set[tuple] = set()

    # 贪心分配：先按顺序，冲突行自动跳过（不重复使用同一行）
    for name, keywords, excludes in targets:
        best = best_match(rows, keywords, excludes)
        if not best:
            missing.append(name)
            continue
        key = (best["category"], best["code"], best["name"])
        if key in used:
            # 尝试次优候选
            candidates = [
                r
                for r in rows
                if (r["category"], r["code"], r["name"]) not in used
                and normalize(r["name"])
                and any(k in normalize(r["name"]) for k in keywords)
                and not any(e in CC.convert(r["name"]) for e in excludes)
            ]
            candidates.sort(
                key=lambda r: (
                    -sum(1 for k in keywords if k in normalize(r["name"])),
                    len(normalize(r["name"])),
                    -int("平均" in r["name"]),
                )
            )
            best = candidates[0] if candidates else None
            if not best:
                missing.append(name)
                continue
            key = (best["category"], best["code"], best["name"])
            if key in used:
                missing.append(name)
                continue
        used.add(key)
        result.append(
            {
                "name": name,
                "caloriesPer100g": round(best["kcal"]),
                "isCustom": False,
            }
        )
        audit.append(
            {
                "name": name,
                "caloriesPer100g": round(best["kcal"]),
                "sourceCategory": best["category"],
                "sourceName": best["name"],
                "sourceCode": best["code"],
            }
        )

    result.sort(key=lambda x: x["name"])
    out_path.write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    audit_path = out_path.with_name(out_path.stem + "_audit.json")
    audit_path.write_text(
        json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"匹配成功: {len(result)} / {len(targets)}")
    print("未匹配:")
    for m in missing:
        print("  -", m)
    print("已写入:", out_path)
    print("审计文件:", audit_path)


if __name__ == "__main__":
    main()
