CC = opencc.OpenCC("t2s")

PREFIXES = ("冷冻", "冷藏", "干", "即食", "市售", "熟", "生", "加热")


def normalize(name: str) -> str:
    s = CC.convert(name)
    s = re.sub(r"[（(]", "", s)
    s = re.sub(r"[)）]", "", s)
    s = re.sub(r"[\s,，、;；\-]", "", s)
    for p in PREFIXES:
        if s.startswith(p) and len(s) > len(p):
            s = s[len(p):]
            break
    if s.endswith("平均值"):
        s = s[: -len("平均值")]
    return s


