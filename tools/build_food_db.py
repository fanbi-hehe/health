def main() -> None:
    if len(sys.argv) < 3:
        print("用法: python tools/build_food_db.py <csv_path> <output_json>")
        sys.exit(1)

    csv_path = Path(sys.argv[1])
    output_path = Path(sys.argv[2])

    # 1. 收集每个食物的“热量”数据（分析項包含“熱量”）
    calories: dict[str, dict] = {}
    heat_analyses = set()
    for row in load_rows(csv_path):
        analysis = (row.get("分析項") or "").strip()
        if "熱量" in analysis or "能量" in analysis:
            heat_analyses.add(analysis)
        food_code = (row.get("整合編號") or "").strip()
        food_name = (row.get("樣品名稱") or "").strip()
        category = (row.get("食品分類") or "").strip()
        if not food_code:
            continue
        key = (category, food_code, food_name)
        calories.setdefault(
            key,
            {"category": category, "code": food_code, "name": food_name, "items": {}},
        )
        item_name = analysis
        if item_name:
            value = (row.get("每100克含量") or "").strip()
            calories[key]["items"][item_name] = value

    print("热量/能量分析项:", sorted(heat_analyses))
    print("食物总数:", len(calories))

    # 2. 找出“热量(kcal)”字段
    def pick_kcal(items: dict) -> float | None:
        for cand in ("熱量", "熱量(kcal)", "熱量(kcal/100g)", "能量(kcal)"):
            v = items.get(cand)
            if v is not None and v not in ("", "-", "0.0", "0"):
                try:
                    return float(v)
                except ValueError:
                    continue
        return None

    rows = []
    for key, info in calories.items():
        kcal = pick_kcal(info["items"])
        if kcal is None:
            continue
        rows.append(
            {
                "category": info["category"],
                "code": info["code"],
                "name": info["name"],
                "kcal": kcal,
            }
        )

    rows.sort(key=lambda r: (r["category"], r["name"]))
    print("有热量数据的食物数:", len(rows))

    # 3. 输出全部有热量数据（供人工筛选）
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print("已写入:", output_path)


if __name__ == "__main__":
    main()
